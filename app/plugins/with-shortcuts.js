const fs = require('fs');
const path = require('path');
const {
  AndroidConfig,
  IOSConfig,
  withAndroidManifest,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require('expo/config-plugins');

/**
 * Home-screen quick actions on both platforms, plus Siri App Shortcuts on iOS.
 *
 * Each action opens a `patchwork://` route (see src/features/shortcuts). The
 * pinned list/board shortcuts, the queue JS drains and Android AppFunctions
 * live in modules/patchwork-shortcuts; this plugin only writes what has to
 * sit in the app itself:
 *
 * - Android: res/xml/patchwork_shortcuts.xml, whose intents need this build's
 *   package name (it differs between the dev and release variants), and the
 *   meta-data on MainActivity that points the launcher at it.
 * - iOS: UIApplicationShortcutItems in Info.plist, and the App Intents file
 *   added to the main target. Xcode reads Siri phrases only from the app
 *   target, so the intents can't ship inside the module's pod.
 */

const ACTIONS = [
  { id: 'new_todo', url: 'patchwork:///new-task', title: 'New To-Do', symbol: 'plus.circle', icon: 'pw_shortcut_add' },
  { id: 'dictate', url: 'patchwork:///?dictate=1', title: 'Dictate', symbol: 'mic', icon: 'pw_shortcut_mic' },
  { id: 'brain_dump', url: 'patchwork:///brain-dump', title: 'Brain Dump', symbol: 'brain.head.profile', icon: 'pw_shortcut_brain_dump' },
  { id: 'search', url: 'patchwork:///search', title: 'Search', symbol: 'magnifyingglass', icon: 'pw_shortcut_search' },
];

const INTENTS_SOURCE = ['modules', 'patchwork-shortcuts', 'app-intents', 'PatchworkAppIntents.swift'];
const INTENTS_FILE = 'PatchworkAppIntents.swift';

function escapeXml(value) {
  return value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

function shortcutsXml(pkg) {
  const items = ACTIONS.map(
    (action) => `    <shortcut
        android:shortcutId="${action.id}"
        android:enabled="true"
        android:icon="@drawable/${action.icon}"
        android:shortcutShortLabel="@string/pw_shortcut_${action.id}_short"
        android:shortcutLongLabel="@string/pw_shortcut_${action.id}_long">
        <intent
            android:action="android.intent.action.VIEW"
            android:data="${escapeXml(action.url)}"
            android:targetPackage="${pkg}"
            android:targetClass="${pkg}.MainActivity" />
    </shortcut>`
  ).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-shortcuts.js. Labels and icons are in modules/patchwork-shortcuts. -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
${items}
</shortcuts>
`;
}

function withAndroidShortcuts(config) {
  config = withDangerousMod(config, [
    'android',
    async (mod) => {
      const pkg = mod.android?.package;
      if (!pkg) throw new Error('with-shortcuts: android.package is required');
      const dir = path.join(mod.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, 'patchwork_shortcuts.xml'), shortcutsXml(pkg));
      return mod;
    },
  ]);
  return withAndroidManifest(config, (mod) => {
    const activity = AndroidConfig.Manifest.getMainActivityOrThrow(mod.modResults);
    AndroidConfig.Manifest.addMetaDataItemToMainApplication(
      activity,
      'android.app.shortcuts',
      '@xml/patchwork_shortcuts',
      'resource'
    );
    return mod;
  });
}

function withIosQuickActions(config) {
  return withInfoPlist(config, (mod) => {
    const bundleId = mod.ios?.bundleIdentifier ?? 'codes.tashhif.patchwork';
    mod.modResults.UIApplicationShortcutItems = ACTIONS.map((action) => ({
      UIApplicationShortcutItemType: `${bundleId}.${action.id}`,
      UIApplicationShortcutItemTitle: action.title,
      UIApplicationShortcutItemIconSymbolName: action.symbol,
      UIApplicationShortcutItemUserInfo: { url: action.url },
    }));
    return mod;
  });
}

function withIosAppIntents(config) {
  config = withDangerousMod(config, [
    'ios',
    async (mod) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
      const target = path.join(mod.modRequest.platformProjectRoot, projectName, INTENTS_FILE);
      await fs.promises.copyFile(path.join(mod.modRequest.projectRoot, ...INTENTS_SOURCE), target);
      return mod;
    },
  ]);
  return withXcodeProject(config, (mod) => {
    const project = mod.modResults;
    const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
    const filepath = `${projectName}/${INTENTS_FILE}`;
    if (!project.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: projectName, project });
    }
    return mod;
  });
}

module.exports = function withShortcuts(config) {
  config = withAndroidShortcuts(config);
  config = withIosQuickActions(config);
  config = withIosAppIntents(config);
  return config;
};
